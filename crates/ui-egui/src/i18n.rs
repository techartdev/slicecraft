//! Interface language: the window's own text through one lookup. English is
//! the source; a missing translation shows the English text.

use std::collections::HashMap;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Language {
    #[default]
    English,
    Bulgarian,
}

impl Language {
    pub const ALL: [Language; 2] = [Language::English, Language::Bulgarian];

    /// Shown in the language's own words.
    pub fn label(self) -> &'static str {
        match self {
            Language::English => "English",
            Language::Bulgarian => "Български",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Language::English => "en",
            Language::Bulgarian => "bg",
        }
    }

    pub fn from_code(s: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|l| l.code() == s.trim())
    }
}

static CURRENT: AtomicU8 = AtomicU8::new(0);

pub fn set_language(l: Language) {
    CURRENT.store(if l == Language::Bulgarian { 1 } else { 0 }, Ordering::Relaxed);
}

pub fn language() -> Language {
    if CURRENT.load(Ordering::Relaxed) == 1 { Language::Bulgarian } else { Language::English }
}

fn bulgarian() -> &'static HashMap<&'static str, &'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| BG.iter().copied().collect())
}

/// The text in the current language.
pub fn tr(s: &str) -> &str {
    match language() {
        Language::English => s,
        Language::Bulgarian => bulgarian().get(s).copied().unwrap_or(s),
    }
}

