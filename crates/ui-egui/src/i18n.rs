#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lookup_falls_back_to_english_and_keys_are_unique() {
        let mut seen = std::collections::HashSet::new();
        for (en, _) in BG {
            assert!(seen.insert(*en), "{en} twice");
        }
        set_language(Language::Bulgarian);
        assert_eq!(tr("Slice"), "Нарязване");
        assert_eq!(tr("no such text"), "no such text");
        set_language(Language::English);
        assert_eq!(tr("Slice"), "Slice");
        assert_eq!(Language::from_code("bg"), Some(Language::Bulgarian));
    }

    #[test]
    fn every_command_and_setting_label_is_translated() {
        let bg = bulgarian();
        let missing: Vec<&str> = slicecraft_engine::COMMANDS
            .iter()
            .map(|c| c.label)
            .chain(slicecraft_doc::settings::SETTINGS.iter().map(|s| s.label))
            .filter(|l| !bg.contains_key(l))
            .collect();
        assert!(missing.is_empty(), "untranslated: {missing:?}");
    }
}
